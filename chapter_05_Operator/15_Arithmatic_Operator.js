// + , _ , * , / , % , **, 


// Assignment Operator

let a = 10;
let b = 20;

// Arithmatic Operator
let c = a + b; // Addition
let d = b - a; // Subtraction
let e = a * b; // Multiplication
let f = b / a; // Division
let g = b % a; // Modulus - it will return the remainder
let h = a ** 2; // Exponentiation - Square of a

console.log("Addition: " + c);
console.log("Subtraction: " + d);
console.log("Multiplication: " + e);
console.log("Division: " + f);
console.log("Modulus: " + g);
console.log("Exponentiation: " + h);



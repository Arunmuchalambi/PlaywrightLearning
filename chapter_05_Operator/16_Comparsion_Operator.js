// comparsion operator (will return boolean value)
let p = 10;
let q = 20;
let r = 10;

console.log("p == r: " + (p == r)); // true
console.log("p === r: " + (p === r)); // true
console.log("p != q: " + (p != q)); // true
console.log("p !== r: " + (p !== r)); // false
console.log("p < q: " + (p < q)); // true
console.log("p > q: " + (p > q)); // false
console.log("p <= r: " + (p <= r)); // true
console.log("p >= q: " + (p >= q)); // false

